async def main():
    os.makedirs(OUT, exist_ok=True)
    for f in glob.glob(os.path.join(OUT, "*.mp3")):
        os.remove(f)
    for key, text in LINES.items():
        parts = [p.strip() for p in text.split("|") if p.strip()]
        for i, part in enumerate(parts, 1):
            name = key if len(parts) == 1 else f"{key}_{i}"
            if part.startswith("~"):
                args = GENTLE
                part = part[1:].strip()
            else:
                args = dict(NORMAL, pitch=PITCHES[i % len(PITCHES)])
            await edge_tts.Communicate(part, VOICE, **args).save(os.path.join(OUT, f"{name}.mp3"))
        print("ok", key, len(parts))

asyncio.run(main())
